// "Ask TypeDB AI": OpenAI ChatKit widget backed by the support-agent edge function in typedb-web.
// Only active when the site is built with the support_agent key (see build-ci.sh); otherwise the
// launcher is inert, as it was with Intercom.
// Leading semicolon guards against the preceding bundled file ending without one.
;(function () {
  "use strict";

  var settings = window.supportAgentSettings;
  var launcher = document.querySelector(".btn-ask-ai");
  if (!settings || !settings.domainKey || !launcher) return;

  var CHATKIT_SCRIPT_URL = "https://cdn.platform.openai.com/deployments/chatkit/chatkit.js";
  var API_URL = "/api/support-agent";
  var USER_ID_KEY = "typedb-support-agent-user";

  var panel = null;
  var chatkit = null;
  var ready = false;
  var sessionUserId = null;

  function randomId() {
    if (window.crypto && crypto.randomUUID) return crypto.randomUUID().replace(/-/g, "");
    var bytes = new Uint8Array(16);
    crypto.getRandomValues(bytes);
    return Array.prototype.map.call(bytes, function (b) { return ("0" + b.toString(16)).slice(-2); }).join("");
  }

  // Anonymous per-browser id so the backend can scope thread history. Falls back to a
  // per-page id when storage is unavailable (private mode, blocked site data).
  function userId() {
    try {
      var id = localStorage.getItem(USER_ID_KEY);
      if (!id) {
        id = randomId();
        localStorage.setItem(USER_ID_KEY, id);
      }
      return id;
    } catch (e) {
      if (!sessionUserId) sessionUserId = randomId();
      return sessionUserId;
    }
  }

  function apiFetch(input, init) {
    init = init || {};
    var headers = new Headers(init.headers || {});
    headers.set("x-support-agent-user", userId());
    return fetch(input, Object.assign({}, init, { headers: headers }));
  }

  function loadChatKit() {
    if (window.customElements && customElements.get("openai-chatkit")) return Promise.resolve();
    if (!document.querySelector('script[src="' + CHATKIT_SCRIPT_URL + '"]')) {
      var script = document.createElement("script");
      script.src = CHATKIT_SCRIPT_URL;
      script.async = true;
      document.head.appendChild(script);
    }
    return customElements.whenDefined("openai-chatkit");
  }

  function chatKitOptions() {
    return {
      api: { url: API_URL, domainKey: settings.domainKey, fetch: apiFetch },
      theme: {
        colorScheme: "dark",
        radius: "soft",
        density: "normal",
        color: {
          accent: { primary: "#02dac9", level: 1 },
          grayscale: { hue: 250, tint: 6, shade: 2 },
        },
      },
      header: {
        title: { text: "Ask TypeDB AI" },
        rightAction: { icon: "close", onClick: closePanel },
      },
      history: { enabled: true, showDelete: true, showRename: false },
      startScreen: {
        greeting: "What would you like to know about TypeDB?",
        prompts: [
          { label: "Install TypeDB", prompt: "How do I install and run TypeDB 3 locally?" },
          { label: "Write a query", prompt: "Show me an example TypeQL match query with a function in TypeDB 3." },
          { label: "What's new", prompt: "What is in the latest TypeDB release?" },
        ],
      },
      composer: {
        placeholder: "Ask a question about TypeDB",
        attachments: { enabled: false },
      },
      threadItemActions: { feedback: true, retry: true },
      disclaimer: { text: "Answers are generated by AI and may be inaccurate. Check the docs before relying on them." },
    };
  }

  function buildPanel() {
    panel = document.createElement("div");
    panel.className = "support-agent-panel";
    panel.setAttribute("role", "dialog");
    panel.setAttribute("aria-label", "Ask TypeDB AI");
    chatkit = document.createElement("openai-chatkit");
    panel.appendChild(chatkit);
    document.body.appendChild(panel);

    chatkit.addEventListener("chatkit.error", function (event) {
      console.error("Ask TypeDB AI:", event.detail && event.detail.error);
    });

    loadChatKit().then(function () {
      chatkit.setOptions(chatKitOptions());
      ready = true;
      if (!panel.hidden) chatkit.focusComposer();
    });
  }

  function openPanel() {
    if (!panel) buildPanel();
    panel.hidden = false;
    document.body.classList.add("support-agent-open");
    launcher.setAttribute("aria-expanded", "true");
    if (ready) chatkit.focusComposer();
  }

  function closePanel() {
    if (!panel) return;
    panel.hidden = true;
    document.body.classList.remove("support-agent-open");
    launcher.setAttribute("aria-expanded", "false");
  }

  function togglePanel() {
    if (panel && !panel.hidden) closePanel();
    else openPanel();
  }

  launcher.setAttribute("aria-expanded", "false");
  launcher.addEventListener("click", function (event) {
    event.preventDefault();
    togglePanel();
  });
  launcher.addEventListener("keydown", function (event) {
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      togglePanel();
    }
  });
  document.addEventListener("keydown", function (event) {
    if (event.key === "Escape") closePanel();
  });
})();
